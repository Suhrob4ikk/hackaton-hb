def _lookup_usage(category: str, language: str):
    category_lower = (category or "").lower()
    morning = None
    evening = None
    generic = None
    for keyword, phase, step, ru_text, tj_text in USAGE_RULES:
        if keyword not in category_lower:
            continue
        text = ru_text if language == "ru" else tj_text
        if phase == "morning" and morning is None:
            morning = (step, text)
        elif phase == "evening" and evening is None:
            evening = (step, text)
        elif phase is None and generic is None:
            generic = (step, text)
    return morning, evening, generic


def _product_instruction_text(category: str, language: str) -> str:
    morning, evening, generic = _lookup_usage(category, language)
    picked = morning or evening or generic
    if picked:
        return picked[1]
    return FALLBACK_INSTRUCTION_RU if language == "ru" else FALLBACK_INSTRUCTION_TJ


def _build_routine(order_products: list[dict], language: str):
    morning_steps: list[tuple[int, str]] = []
    evening_steps: list[tuple[int, str]] = []
    for product in order_products:
        morning, evening, _generic = _lookup_usage(product["category"], language)
        if morning:
            morning_steps.append((morning[0] or 50, f"{product['title']}"))
        if evening:
            evening_steps.append((evening[0] or 50, f"{product['title']}"))
    morning_steps.sort(key=lambda item: item[0])
    evening_steps.sort(key=lambda item: item[0])
    return [title for _, title in morning_steps], [title for _, title in evening_steps]


class InstructionPDF(FPDF):
    def __init__(self, texts: dict):
        super().__init__(format="A4")
        self.texts = texts
        self.set_auto_page_break(auto=True, margin=20)
        self.add_font("DejaVu", "", str(FONT_REGULAR))
        self.add_font("DejaVu", "B", str(FONT_BOLD))
        self.set_margins(18, 16, 18)

    def header(self):
        self.set_fill_color(*PINK)
        self.rect(0, 0, self.w, 3, style="F")

    def footer(self):
        self.set_y(-15)
        self.set_font("DejaVu", "", 8.5)
        self.set_text_color(*MUTED)
        self.cell(0, 8, self.texts["footer"], align="C")


def generate_instruction_pdf(order: dict, language: str, catalog) -> bytes:
    """Build the instructions PDF for a completed demo order.

    `order` is the session's last_order snapshot: {id, items, total, created_at}.
    `items` entries carry id/title/price/volume/quantity as returned by the cart API.
    Full product records (for category-based usage lookup) are re-fetched from
    the catalog so the frontend never needs to know about categories.
    """
    texts = TEXTS.get(language, TEXTS["ru"])

    order_products = []
    for item in order["items"]:
        product = catalog.get(item["id"]) or {}
        order_products.append({
            "title": item["title"],
            "volume": format_volume(product.get("volume")) or item.get("volume"),
            "quantity": item["quantity"],
            "category": product.get("category", ""),
        })

    pdf = InstructionPDF(texts)
    pdf.add_page()

    pdf.set_text_color(*INK)
    pdf.set_font("DejaVu", "B", 20)
    pdf.cell(0, 10, texts["brand"], new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("DejaVu", "", 12.5)
    pdf.set_text_color(*BODY)
    pdf.cell(0, 8, texts["heading"], new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)

    pdf.set_draw_color(*BORDER)
    pdf.line(pdf.get_x(), pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(6)

    pdf.set_font("DejaVu", "", 10.5)
    pdf.set_text_color(*MUTED)
    pdf.cell(0, 6, texts["order_label"], new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("DejaVu", "B", 13)
    pdf.set_text_color(*INK)
    pdf.cell(0, 7, f"#{order['id']}", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(6)

    pdf.set_font("DejaVu", "B", 13.5)
    pdf.set_text_color(*INK)
    pdf.cell(0, 8, texts["products_heading"], new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    for index, product in enumerate(order_products, start=1):
        pdf.set_font("DejaVu", "B", 11.5)
        pdf.set_text_color(*INK)
        title_line = f"{index}. {product['title']}"
        if product["quantity"] and product["quantity"] > 1:
            title_line += f"  x{product['quantity']}"
        pdf.multi_cell(0, 6.5, title_line, new_x="LMARGIN", new_y="NEXT")

        if product["volume"]:
            pdf.set_font("DejaVu", "", 9.5)
            pdf.set_text_color(*MUTED)
            pdf.cell(0, 5.5, product["volume"], new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("DejaVu", "B", 9.5)
        pdf.set_text_color(*BODY)
        pdf.cell(0, 6, texts["how_to_use"], new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("DejaVu", "", 10)
        pdf.set_text_color(*INK)
        pdf.multi_cell(0, 5.8, _product_instruction_text(product["category"], language))
        pdf.ln(3)

    morning_steps, evening_steps = _build_routine(order_products, language)
    if morning_steps or evening_steps:
        pdf.ln(2)
        pdf.set_draw_color(*BORDER)
        pdf.line(pdf.get_x(), pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
        pdf.ln(6)

        pdf.set_font("DejaVu", "B", 13.5)
        pdf.set_text_color(*INK)
        pdf.cell(0, 8, texts["routine_heading"], new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2)

        for label, steps in ((texts["morning"], morning_steps), (texts["evening"], evening_steps)):
            if not steps:
                continue
            pdf.set_font("DejaVu", "B", 11)
            pdf.set_text_color(*PINK if label == texts["morning"] else VIOLET)
            pdf.cell(0, 7, label, new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("DejaVu", "", 10)
            pdf.set_text_color(*INK)
            for step_index, step_title in enumerate(steps, start=1):
                pdf.multi_cell(0, 6, f"{step_index}. {step_title}", new_x="LMARGIN", new_y="NEXT")
            pdf.ln(2)

    pdf.ln(2)
    pdf.set_draw_color(*BORDER)
    pdf.line(pdf.get_x(), pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(6)

    pdf.set_font("DejaVu", "B", 12)
    pdf.set_text_color(*INK)
    pdf.cell(0, 7, texts["extra_heading"], new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("DejaVu", "", 10)
    pdf.set_text_color(*BODY)
    pdf.multi_cell(0, 5.8, texts["extra_text"])

    return bytes(pdf.output())
