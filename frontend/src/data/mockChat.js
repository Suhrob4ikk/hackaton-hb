const KEYWORD_CATEGORIES = [
  { category: 'dry', keywords: ['сух', 'dry'] },
  { category: 'oily', keywords: ['жирн', 'oily'] },
  { category: 'sensitive', keywords: ['чувствит', 'раздраж', 'sensitive'] },
  { category: 'combination', keywords: ['комбинир', 'смешан'] },
  { category: 'hair', keywords: ['волос', 'hair', 'локон'] },
]

export function detectCategory(message) {
  const text = message.toLowerCase()
  const match = KEYWORD_CATEGORIES.find(({ keywords }) =>
    keywords.some((keyword) => text.includes(keyword)),
  )
  return match?.category ?? null
}

